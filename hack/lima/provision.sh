#!/usr/bin/env bash
# Provision the fastvm Lima VM and (re)start fastvmd inside it (docs/MACOS.md).
#
# Runs as root inside the VM; hack/lima/fastvm-lima.sh invokes it on every
# `up`/`start`. Idempotent: packages, Cloud Hypervisor, and the CoW filesystem
# are only installed/created when missing (the loop mount is re-attached after a
# VM reboot), and the config and systemd unit are rewritten each run.
#
# Environment (set by the wrapper):
#   FASTVM_REPO   repository checkout, mounted from the Mac at the same path
#   FASTVM_STATE  host state dir with certs/ (mounted read-only)
#   FASTVM_HOME   the Mac user's $HOME (Lima mounts it at the same path)
#   FASTVM_BIN    linux/arm64 binaries dir (default $FASTVM_REPO/bin/linux-arm64)
set -euo pipefail

REPO="${FASTVM_REPO:?FASTVM_REPO is required}"
STATE="${FASTVM_STATE:?FASTVM_STATE is required}"
HOST_HOME="${FASTVM_HOME:?FASTVM_HOME is required}"
BINDIR="${FASTVM_BIN:-$REPO/bin/linux-arm64}"

# Pinned Cloud Hypervisor release (static aarch64 build).
CH_VERSION="v55.0"
CH_SHA256="446de7552dacc83bc86d1137e7ffa7c2d204cdda4850eac4f2d2666d63c0f697"
CH_URL="https://github.com/cloud-hypervisor/cloud-hypervisor/releases/download/$CH_VERSION/cloud-hypervisor-static-aarch64"
CH_BIN=/usr/local/bin/cloud-hypervisor

COW_IMG=/var/lib/fastvm-cow.img
COW_MNT=/var/lib/fastvm-cow
COW_SIZE=40G
DATA_DIR="$COW_MNT/data"
CONFIG=/etc/fastvm/config.yaml
SOCKET=/run/fastvm/fastvm.sock

die() { echo "provision: error: $*" >&2; exit 1; }
log() { echo "provision: $*"; }

[[ "$(id -u)" -eq 0 ]] || die "run as root"
[[ "$(uname -m)" == aarch64 ]] || die "expected an aarch64 VM, got $(uname -m)"
[[ -e /dev/kvm ]] || die "/dev/kvm is missing: nested virtualization is unavailable.
  It needs an Apple M3 or newer chip, macOS 15+, and Lima's vz driver with
  nestedVirtualization: true (hack/lima/fastvm.yaml)."
for f in fastvmd fastvm-agent; do
	[[ -x "$BINDIR/$f" ]] || die "missing $BINDIR/$f (run: make mac-build)"
done
[[ -f "$REPO/test/e2e/assets/vmlinux.bin" ]] || die "missing guest kernel (run: FASTVM_ARCH=arm64 make assets)"
[[ -f "$STATE/certs/server/cert.pem" ]] || die "missing API certs in $STATE/certs (the wrapper creates them)"

# --- packages -----------------------------------------------------------------
pkgs=()
command -v nft >/dev/null || pkgs+=(nftables)
command -v mkfs.xfs >/dev/null || pkgs+=(xfsprogs)
[[ -x /usr/libexec/virtiofsd || -x /usr/lib/virtiofsd ]] || command -v virtiofsd >/dev/null || pkgs+=(virtiofsd)
command -v curl >/dev/null || pkgs+=(curl ca-certificates)
if ((${#pkgs[@]})); then
	log "installing ${pkgs[*]}"
	export DEBIAN_FRONTEND=noninteractive
	apt-get update -qq
	apt-get install -y -qq "${pkgs[@]}" >/dev/null
fi
VIRTIOFSD="$(command -v virtiofsd || true)"
for p in /usr/libexec/virtiofsd /usr/lib/virtiofsd; do
	[[ -z "$VIRTIOFSD" && -x "$p" ]] && VIRTIOFSD="$p"
done
[[ -n "$VIRTIOFSD" ]] || die "virtiofsd not found after install"

# --- Cloud Hypervisor -----------------------------------------------------------
if [[ ! -x "$CH_BIN" ]] || [[ "$(sha256sum "$CH_BIN" | cut -d' ' -f1)" != "$CH_SHA256" ]]; then
	log "installing Cloud Hypervisor $CH_VERSION"
	curl -fsSL --retry 3 -o "$CH_BIN.tmp" "$CH_URL"
	got="$(sha256sum "$CH_BIN.tmp" | cut -d' ' -f1)"
	[[ "$got" == "$CH_SHA256" ]] || { rm -f "$CH_BIN.tmp"; die "Cloud Hypervisor SHA-256 mismatch: got $got"; }
	chmod 0755 "$CH_BIN.tmp"
	mv "$CH_BIN.tmp" "$CH_BIN"
fi

# --- CoW filesystem (XFS reflink on a sparse loop image) -------------------------
FASTVM_COW_IMG="$COW_IMG" FASTVM_COW_MNT="$COW_MNT" FASTVM_COW_SIZE="$COW_SIZE" \
	"$REPO/hack/setup-cow-fs.sh" setup >/dev/null

# --- daemon config ------------------------------------------------------------------
# Only overrides; everything else uses the built-in defaults (internal/config).
mkdir -p /etc/fastvm
cat >"$CONFIG.tmp" <<EOF
# Generated by hack/lima/provision.sh; rewritten on every start.
data_dir: $DATA_DIR
socket_path: $SOCKET
kernel_path: $REPO/test/e2e/assets/vmlinux.bin
agent_path: $BINDIR/fastvm-agent

vmm:
  binary: $CH_BIN
  virtiofsd: $VIRTIOFSD

# Host-directory volumes must live under a Lima mount: the Mac's home
# (read-only) or /tmp/lima (writable).
volumes:
  allowed_host_prefixes:
    - $HOST_HOME
    - /tmp/lima

volume:
  cow: reflink

switch:
  # Bridge: egress allowlists (--allow-host) are not supported in eBPF mode yet.
  mode: bridge

api:
  host: 127.0.0.1:8443
  cert_path: $STATE/certs/server
EOF
mv "$CONFIG.tmp" "$CONFIG"

# --- systemd unit -------------------------------------------------------------------
cat >/etc/systemd/system/fastvmd.service <<EOF
[Unit]
Description=fastvm daemon (Lima dev VM, docs/MACOS.md)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=$BINDIR/fastvmd --config $CONFIG
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable fastvmd >/dev/null 2>&1
log "restarting fastvmd"
systemctl restart fastvmd

for _ in $(seq 1 50); do
	[[ -S "$SOCKET" ]] && { log "fastvmd is up ($SOCKET, API 127.0.0.1:8443)"; exit 0; }
	sleep 0.2
done
journalctl -u fastvmd -n 30 --no-pager >&2 || true
die "fastvmd did not create $SOCKET"
